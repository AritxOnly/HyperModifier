#!/usr/bin/env python3
"""Generate conservative ARM64 ABI contracts from a reviewed schema ELF.
The mini debug symbols are used only offline to include private clone/drop helpers.
At runtime no debug data, disassembler, library hash or fixed RVA is required.
"""
import argparse, struct, lzma, sys
sys.dont_write_bytecode = True
from pathlib import Path
from schema_elf import Elf, names

def signed(v,b): return v-(1<<b) if v & (1<<(b-1)) else v

def generate(path, selected_names=None, namespace="schema_abi"):
 names = selected_names if selected_names is not None else globals()["names"]
 e=Elf(Path(path).read_bytes());dbg=Elf(lzma.decompress(e.section('.gnu_debugdata')))
 roots=[e.syms[n] for n in names];nodes=list(roots);seen={a:i for i,(a,_) in enumerate(nodes)}
 edges=[];hashes=[]
 # Recover each PLT slot's semantic import from its GOT relocation.
 ds=e.ss['.dynsym'];ss=e.ss['.dynstr'];strings=e.section('.dynstr');imports={}
 for off,info,addend in struct.iter_unpack('<QQq',e.section('.rela.plt')):
  no=struct.unpack_from('<I',e.d,ds[4]+(info>>32)*24)[0]
  imports[off]=strings[no:].split(b'\0',1)[0].decode()
 def imported(t):
  w0,w1=struct.unpack('<II',e.read(t,8))
  if w0&0x9f00001f!=0x90000010 or w1&0xffc003ff!=0xf9400211:return None
  page=(t&~4095)+(signed((((w0>>5)&0x7ffff)<<2)|((w0>>29)&3),21)<<12)
  return imports.get(page+((w1>>10)&4095)*8)
 for index,(a,size) in enumerate(nodes):
  h=0xcbf29ce484222325
  for i,w in enumerate(struct.unpack('<'+'I'*(size//4),e.read(a,size))):
   if w&0x7c000000==0x14000000:
    target=a+i*4+signed(w&0x3ffffff,26)*4
    if not a<=target<a+size:
     symbol=imported(target)
     if symbol:edge=(index,i,-1,symbol)
     else:
      if target not in dbg.byaddr:raise ValueError('Unresolved branch '+hex(target))
      if target not in seen:
       seen[target]=len(nodes);nodes.append((target,dbg.byaddr[target][1]))
      edge=(index,i,seen[target],None)
     edges.append(edge);w &= 0xfc000000
   elif w&0x9f000000==0x10000000:
    # These three ADRs address Rust panic source locations, not object fields.
    if index < len(roots):raise ValueError('Review new public ADR')
    w &= 0x9f00001f
   for byte in struct.pack('<I',w):h=((h^byte)*0x100000001b3)&0xffffffffffffffff
  hashes.append(h)
 out=['// Generated by tools/analysis/generate-schema-abi.py; review before regenerating.','#pragma once','#include "schema_abi_types.h"','namespace '+namespace+' {','inline constexpr Function functions[] = {']
 for i,((a,size),h) in enumerate(zip(nodes,hashes)):
  name='"'+names[i]+'"' if i<len(roots) else 'nullptr'
  out.append(f'    {{{name}, {size}, 0x{h:016x}ULL}},')
 out+=['};','inline constexpr Edge edges[] = {']
 for f,w,t,s in edges:out.append(f'    {{{f}, {w}, {t}, '+('"'+s+'"' if s else 'nullptr')+'},')
 out+=['};',f'inline constexpr size_t rootCount = {len(roots)};','inline constexpr Contract contract{functions, std::size(functions), edges, std::size(edges), rootCount};','}']
 return '\n'.join(out)+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('elf');p.add_argument('output');p.add_argument('--roots', nargs='+');p.add_argument('--namespace', default='schema_abi');a=p.parse_args();Path(a.output).write_text(generate(a.elf,a.roots,a.namespace))
