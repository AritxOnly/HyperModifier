    /** Called on settings load, never on draw/touch/animation callbacks. */
    static String migrateCompactXml(String xml) {
        if (xml == null || xml.isBlank()) return "";
        if (xml.hashCode() != -748236290 && xml.hashCode() != -968639550) return xml;
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256")
                    .digest(xml.getBytes(StandardCharsets.UTF_8));
            StringBuilder hash = new StringBuilder(64);
            for (byte b : digest) {
                hash.append(Character.forDigit((b >>> 4) & 15, 16));
                hash.append(Character.forDigit(b & 15, 16));
            }
            return hash.toString().equals("2f9816a19fd7819caf7e8a601d9f0cc90d4b2b64a58549c4a5b3fff6b1b2502c") || hash.toString().equals("06c03c063c009c24413e7fed8c68037c46edc1f06a34da10eda4a000aee42c72") ? "" : xml;
        } catch (java.security.NoSuchAlgorithmException ignored) {
            return xml;
        }
    }

